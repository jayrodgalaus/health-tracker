import { expect, test } from '@playwright/test'

test('daily radar finishes with connected nodes and honors reduced motion', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Track what matters to you.' })).toBeVisible()
  await page.getByRole('textbox', { name: 'Date of birth' }).fill('1990-03-12')
  await page.getByLabel('Height (cm)').fill('170')
  await page.getByLabel(/Initial measured weight/).fill('70')
  await page.getByLabel('Primary goal').selectOption('maintain')
  await page.getByRole('button', { name: 'Create local profile' }).click()
  await page.goto('/settings/goals')
  await page.getByLabel('Optional calorie target (kcal/day)').fill('1600')
  await page.getByLabel('Optional protein target (g/day)').fill('100')
  await page.getByLabel('Optional fiber target (g/day)').fill('25')
  await page.getByRole('button', { name: 'Save goals' }).click()
  await page.goto('/log/food')
  await page.getByRole('combobox', { name: 'Name' }).fill('Synthetic radar food')
  await page.getByLabel('Calories (kcal)').fill('1600')
  await page.getByLabel('Protein (g)').fill('80')
  await page.getByLabel('Fiber (g)').fill('18')
  await page.getByRole('button', { name: 'Add to log' }).click()
  await page.goto('/today')
  const chart = page.getByRole('button', { name: 'Show daily goal details' })
  const svg = chart.locator('svg[data-radar-animation]')
  await expect(svg).toHaveAttribute('data-radar-animation', 'settled')
  await expect(svg.locator('[data-radar-point]')).toHaveCount(3)
  const shape = svg.locator('[data-radar-shape="complete"]')
  await expect(shape).toHaveAttribute('stroke', '#ffffff')
  const points = await shape.getAttribute('points')
  expect(points).toBeTruthy()
  expect(points).not.toBe('160.00,150.00 160.00,150.00 160.00,150.00')
  await chart.click()
  await expect(shape).toHaveAttribute('points', points!)
})
