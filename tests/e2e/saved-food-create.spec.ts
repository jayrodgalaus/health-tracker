import { expect, test, type Page } from '@playwright/test'

async function onboard(page: Page) {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Track what matters to you.' })).toBeVisible()
  await page.getByRole('textbox', { name: 'Date of birth' }).fill('1990-03-12')
  await page.getByLabel('Height (cm)').fill('170')
  await page.getByLabel(/Initial measured weight/).fill('70')
  await page.getByLabel('Primary goal').selectOption('maintain')
  await page.getByRole('button', { name: 'Create local profile' }).click()
  await expect(page.getByRole('heading', { name: 'Daily goal alignment' })).toBeVisible()
}

test('Save a food and Save a drink open standalone pages; cancelling returns to the selected tab', async ({ page }) => {
  await onboard(page)
  const date = '2026-01-15'
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/log/saved-foods?date=' + date)

  const createFood = page.getByRole('link', { name: '+ Save a food' })
  await expect(createFood).toHaveAttribute('href', '/log/saved-foods/new/food?date=' + date)
  await createFood.click()
  await expect(page).toHaveURL('/log/saved-foods/new/food?date=' + date)
  await expect(page.getByRole('heading', { name: 'Save a food', exact: true })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Product type' })).toHaveValue('food')
  const foodForm = page.locator('#main-content form')
  await expect(foodForm).toHaveCount(1)
  await expect(foodForm).toHaveCSS('border-top-width', '0px')
  await page.getByLabel('Product name').fill('Unsaved draft')
  await page.getByRole('button', { name: 'Cancel' }).click()
  await expect(page).toHaveURL('/log/saved-foods?date=' + date + '&kind=food')
  await expect(page.getByRole('tab', { name: 'Foods' })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByText('No saved foods yet.')).toBeVisible()

  await page.getByRole('tab', { name: 'Drinks' }).click()
  const createDrink = page.getByRole('link', { name: '+ Save a drink' })
  await expect(createDrink).toHaveAttribute('href', '/log/saved-foods/new/drink?date=' + date)
  await createDrink.click()
  await expect(page).toHaveURL('/log/saved-foods/new/drink?date=' + date)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Save a drink', exact: true })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Product type' })).toHaveValue('beverage')
  await expect(page.getByLabel('Fluid volume per reference portion (ml)')).toBeVisible()
  await page.getByRole('link', { name: /Back to Saved Foods and Drinks/ }).click()
  await expect(page).toHaveURL('/log/saved-foods?date=' + date + '&kind=drink')
  await expect(page.getByRole('tab', { name: 'Drinks' })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByText('No saved drinks yet.')).toBeVisible()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
  expect(overflow).toBeLessThanOrEqual(2)
})

test('direct save page keeps local validation and returns to the matching saved-items tab', async ({ page }) => {
  await onboard(page)
  const date = '2026-01-15'
  await page.goto('/log/saved-foods/new/food?date=' + date)
  await page.getByRole('button', { name: 'Save label' }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await page.getByLabel('Product name').fill('Synthetic saved snack')
  await page.getByLabel('Calories (kcal)').fill('85')
  await page.getByRole('button', { name: 'Save label' }).click()
  await expect(page).toHaveURL('/log/saved-foods?date=' + date + '&kind=food')
  await expect(page.getByRole('heading', { name: 'Synthetic saved snack' })).toBeVisible()
  await expect(page.getByTestId('app-toast')).toContainText('Label saved.')

  await page.goto('/log/saved-foods/new/drink?date=' + date)
  await page.getByLabel('Product name').fill('Synthetic saved beverage')
  await page.getByLabel('Calories (kcal)').fill('50')
  await page.getByLabel('Fluid volume per reference portion (ml)').fill('240')
  await page.getByRole('button', { name: 'Save label' }).click()
  await expect(page).toHaveURL('/log/saved-foods?date=' + date + '&kind=drink')
  await expect(page.getByRole('heading', { name: 'Synthetic saved beverage' })).toBeVisible()
  await expect(page.getByRole('tab', { name: 'Drinks' })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('button', { name: 'Edit label' }).click()
  await expect(page.getByLabel('Calories (kcal)')).toHaveValue('50')
  await expect(page.getByLabel('Fluid volume per reference portion (ml)')).toHaveValue('240')
})
